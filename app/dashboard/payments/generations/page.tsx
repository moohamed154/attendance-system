import { getSession } from '@/lib/auth';
import { redirect } from 'next/navigation';
import { getGenerationHistory } from '@/actions/payments/subscriptions';
import { Card } from '@/components/ui/card';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table';
import { Badge } from '@/components/ui/badge';
import dayjs from 'dayjs';
import { GenerationsActions } from '../../../../components/payments/generations-actions';
import { getDictionary } from '@/lib/i18n';
import 'dayjs/locale/ar';

export const metadata = {
  title: 'Monthly Generations History',
};

export default async function GenerationsPage() {
  const session = await getSession();
  const dict = await getDictionary();
  const t = dict.generationHistoryPage || {};

  if (session?.role !== 'ADMIN') {
    redirect('/dashboard/payments');
  }

  const generations = await getGenerationHistory();
  // Ensure dayjs uses the correct locale if it's set globally or we can set it here based on something. 
  // For now we assume dayjs handles locales properly or we just format it.
  
  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-3xl font-bold tracking-tight">{t.pageTitle || 'Generation History'}</h1>
        <p className="text-muted-foreground mt-1">{t.subtitle || 'View past monthly subscription generations and retry failures.'}</p>
      </div>

      <Card className="rounded-2xl border-border/50 shadow-sm overflow-hidden bg-card">
        <div className="overflow-x-auto">
          <Table>
            <TableHeader>
              <TableRow className="bg-muted/30">
                <TableHead className="text-start">{t.month || 'Month'}</TableHead>
                <TableHead className="text-start">{t.generatedAt || 'Generated At'}</TableHead>
                <TableHead className="text-start">{t.generatedBy || 'Generated By'}</TableHead>
                <TableHead className="text-start">{t.subscriptions || 'Subscriptions'}</TableHead>
                <TableHead className="text-start">{t.revenue || 'Revenue'}</TableHead>
                <TableHead className="text-start">{t.status || 'Status'}</TableHead>
                <TableHead className="text-right">{t.actions || 'Actions'}</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {generations.length === 0 ? (
                <TableRow>
                  <TableCell colSpan={7} className="text-center p-8 text-muted-foreground">
                    {t.noGenerations || 'No generations found.'}
                  </TableCell>
                </TableRow>
              ) : (
                generations.map((gen) => (
                  <TableRow key={gen.id} className="hover:bg-muted/20">
                    <TableCell className="text-start font-medium">
                      {dayjs(new Date(gen.year, gen.month - 1)).format('MMMM YYYY')}
                    </TableCell>
                    <TableCell className="text-start text-sm text-muted-foreground">
                      {dayjs(gen.startedAt).format('MMM D, YYYY h:mm A')}
                      {gen.executionTime && <span className="block text-xs text-muted-foreground/50">{(t.took || 'Took {time}s').replace('{time}', (gen.executionTime / 1000).toFixed(1))}</span>}
                    </TableCell>
                    <TableCell className="text-start font-medium text-muted-foreground">
                      {gen.generatedBy?.username || t.system || 'System'}
                    </TableCell>
                    <TableCell className="text-start">
                      <div className="flex flex-col gap-1 text-sm">
                        <span className="text-green-600 font-semibold">{(t.created || '{count} Created').replace('{count}', gen.createdCount.toString())}</span>
                        {gen.failedCount > 0 && <span className="text-red-500 font-semibold">{(t.failed || '{count} Failed').replace('{count}', gen.failedCount.toString())}</span>}
                        {gen.skippedCount > 0 && <span className="text-yellow-600">{(t.skipped || '{count} Skipped').replace('{count}', gen.skippedCount.toString())}</span>}
                      </div>
                    </TableCell>
                    <TableCell className="text-start font-semibold">
                      {gen.expectedRevenue} {(dict as any).general?.currency || 'EGP'}
                    </TableCell>
                    <TableCell className="text-start">
                      <Badge 
                        variant="outline" 
                        className={
                          gen.status === 'COMPLETED' ? 'border-green-500/30 text-green-600 bg-green-500/10' :
                          gen.status === 'RUNNING' ? 'border-blue-500/30 text-blue-600 bg-blue-500/10' :
                          'border-red-500/30 text-red-600 bg-red-500/10'
                        }
                      >
                        {(dict as any).general?.status?.[gen.status] || gen.status.replace(/_/g, ' ')}
                      </Badge>
                    </TableCell>
                    <TableCell className="text-right">
                      <GenerationsActions snapshot={gen} />
                    </TableCell>
                  </TableRow>
                ))
              )}
            </TableBody>
          </Table>
        </div>
      </Card>
    </div>
  );
}
