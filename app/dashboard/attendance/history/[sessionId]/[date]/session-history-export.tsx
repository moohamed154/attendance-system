'use client';

import { Button } from '@/components/ui/button';
import { Download } from 'lucide-react';
import * as XLSX from 'xlsx';
import dayjs from 'dayjs';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

export function SessionHistoryExport({ attendances, session, date, dict }: any) {
  const exportXLSX = () => {
    try {
      const wb = XLSX.utils.book_new();
      
      const localizedData = attendances.map((a: any) => ({
        [dict.historyPage.studentColumns.id]: a.student.studentId,
        [dict.historyPage.studentColumns.name]: a.student.name,
        [dict.historyPage.studentColumns.status]: dict.historyPage.status[a.status.toLowerCase() as keyof typeof dict.historyPage.status],
        [dict.historyPage.studentColumns.recordedAt]: dayjs(a.updatedAt).format('h:mm A'),
      }));

      const ws = XLSX.utils.json_to_sheet(localizedData);
      XLSX.utils.book_append_sheet(wb, ws, "Session History");
      XLSX.writeFile(wb, `session_history_${session.grade}_${dayjs(date).format('YYYY-MM-DD')}.xlsx`);
    } catch (error) {
      console.error(error);
    }
  };

  const exportPDF = () => {
    try {
      const pdf = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
      });

      const pageWidth = pdf.internal.pageSize.getWidth();

      // Header
      pdf.setFontSize(18);
      pdf.setTextColor(37, 99, 235);
      pdf.text(dict.historyPage.sessionDetails || "Session Details", pageWidth / 2, 20, { align: 'center' });

      // Session info
      pdf.setFontSize(11);
      pdf.setTextColor(85, 85, 85);
      const info = `${dayjs(date).format('MMMM D, YYYY')}  •  ${session.grade}  •  ${session.time}`;
      pdf.text(info, pageWidth / 2, 28, { align: 'center' });

      // Divider
      pdf.setDrawColor(37, 99, 235);
      pdf.setLineWidth(0.5);
      pdf.line(14, 32, pageWidth - 14, 32);

      // Table
      const head = [
        dict.historyPage.studentColumns.id || "ID",
        dict.historyPage.studentColumns.name || "Name",
        dict.historyPage.studentColumns.status || "Status",
        dict.historyPage.studentColumns.recordedAt || "Recorded At",
      ];

      const body = attendances.map((a: any) => {
        const statusText = dict.historyPage.status[a.status.toLowerCase() as keyof typeof dict.historyPage.status] || a.status;
        return [
          a.student.studentId,
          a.student.name,
          statusText,
          dayjs(a.updatedAt).format('h:mm A'),
        ];
      });

      autoTable(pdf, {
        startY: 38,
        head: [head],
        body: body,
        theme: 'grid',
        headStyles: {
          fillColor: [37, 99, 235],
          textColor: [255, 255, 255],
          fontStyle: 'bold',
          halign: 'center',
        },
        bodyStyles: {
          halign: 'center',
        },
        alternateRowStyles: {
          fillColor: [248, 249, 250],
        },
        margin: { left: 14, right: 14 },
      });

      // Footer
      const pageHeight = pdf.internal.pageSize.getHeight();
      pdf.setFontSize(8);
      pdf.setTextColor(107, 114, 128);
      pdf.text("Generated by Attendance System", 14, pageHeight - 10);
      pdf.text(`Date: ${new Date().toLocaleDateString()}`, pageWidth - 14, pageHeight - 10, { align: 'right' });

      pdf.save(`session_history_${session.grade}_${dayjs(date).format('YYYY-MM-DD')}.pdf`);
    } catch (error) {
      console.error("PDF Export Error: ", error);
      alert(`Failed to export PDF: ${error instanceof Error ? error.message : String(error)}`);
    }
  };

  return (
    <div className="flex items-center gap-2 print:hidden">
      <Button variant="outline" size="sm" onClick={exportXLSX} className="rounded-xl">
        <Download className="w-4 h-4 rtl:ml-2 ltr:mr-2" />
        {dict.historyPage.exportExcel}
      </Button>
      <Button variant="outline" size="sm" onClick={exportPDF} className="rounded-xl">
        <Download className="w-4 h-4 rtl:ml-2 ltr:mr-2" />
        {dict.historyPage.exportPdf}
      </Button>
    </div>
  );
}
