'use client';

import { useState } from 'react';
import { Button } from '@/components/ui/button';
import { Download, Loader2 } from 'lucide-react';
import * as XLSX from 'xlsx';
import dayjs from 'dayjs';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { convertArabic } from 'arabic-reshaper';

function hasArabic(text: string): boolean {
  return /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/.test(text);
}

function processArabicText(text: string): string {
  if (!text) return '';
  const words = text.split(' ');
  const processedWords = words.map(word => {
    if (hasArabic(word)) {
      const reshaped = convertArabic(word);
      return reshaped.split('').reverse().join('');
    }
    return word;
  });
  return processedWords.reverse().join(' ');
}

function pdfText(text: string, isArabic: boolean): string {
  if (!isArabic || !text) return text || '';
  return processArabicText(text);
}

async function loadArabicFont(pdf: jsPDF) {
  const res = await fetch('/fonts/Amiri-Regular.ttf');
  const buffer = await res.arrayBuffer();
  const base64 = btoa(
    new Uint8Array(buffer).reduce((data, byte) => data + String.fromCharCode(byte), '')
  );
  pdf.addFileToVFS('Amiri-Regular.ttf', base64);
  pdf.addFont('Amiri-Regular.ttf', 'Amiri', 'normal');
  pdf.setFont('Amiri');
}

export function SessionHistoryExport({ attendances, session, date, dict }: any) {
  const isArabic = dict?.nav?.today === "اليوم";
  const [isExportingExcel, setIsExportingExcel] = useState(false);
  const [isExportingPdf, setIsExportingPdf] = useState(false);

  const exportXLSX = async () => {
    setIsExportingExcel(true);
    try {
      const wb = XLSX.utils.book_new();
      
      const localizedData = attendances.map((a: any) => ({
        [dict.historyPage.studentColumns.id]: a.student.studentId,
        [dict.historyPage.studentColumns.name]: a.student.name,
        [dict.historyPage.studentColumns.status]: dict.historyPage.status[a.status.toLowerCase() as keyof typeof dict.historyPage.status],
        [dict.historyPage.studentColumns.recordedAt]: dayjs(a.updatedAt).format('h:mm A'),
      }));

      const ws = XLSX.utils.json_to_sheet(localizedData);
      XLSX.utils.book_append_sheet(wb, ws, "Session History");
      XLSX.writeFile(wb, `session_history_${session.grade}_${dayjs(date).format('YYYY-MM-DD')}.xlsx`);
    } catch (error) {
      console.error(error);
    } finally {
      setIsExportingExcel(false);
    }
  };

  const exportPDF = async () => {
    setIsExportingPdf(true);
    try {
      const pdf = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
      });

      const pageWidth = pdf.internal.pageSize.getWidth();

      if (isArabic) {
        await loadArabicFont(pdf);
      }

      // Header
      pdf.setFontSize(18);
      pdf.setTextColor(37, 99, 235);
      pdf.text(pdfText(dict.historyPage.sessionDetails || "Session Details", isArabic), pageWidth / 2, 20, { align: 'center' });

      // Session info
      pdf.setFontSize(11);
      pdf.setTextColor(85, 85, 85);
      const info = `${dayjs(date).format('MMMM D, YYYY')}  •  ${session.grade}  •  ${session.time}`;
      pdf.text(pdfText(info, isArabic), pageWidth / 2, 28, { align: 'center' });

      // Divider
      pdf.setDrawColor(37, 99, 235);
      pdf.setLineWidth(0.5);
      pdf.line(14, 32, pageWidth - 14, 32);

      // Table
      const head = [
        pdfText(dict.historyPage.studentColumns.id || "ID", isArabic),
        pdfText(dict.historyPage.studentColumns.name || "Name", isArabic),
        pdfText(dict.historyPage.studentColumns.status || "Status", isArabic),
        pdfText(dict.historyPage.studentColumns.recordedAt || "Recorded At", isArabic),
      ];

      const body = attendances.map((a: any) => {
        const statusText = dict.historyPage.status[a.status.toLowerCase() as keyof typeof dict.historyPage.status] || a.status;
        return [
          a.student.studentId,
          pdfText(a.student.name, isArabic),
          pdfText(statusText, isArabic),
          dayjs(a.updatedAt).format('h:mm A'),
        ];
      });

      const fontName = isArabic ? 'Amiri' : 'helvetica';

      autoTable(pdf, {
        startY: 38,
        head: [head],
        body: body,
        theme: 'grid',
        styles: {
          font: fontName,
          halign: 'center',
        },
        headStyles: {
          fillColor: [37, 99, 235],
          textColor: [255, 255, 255],
          fontStyle: 'bold',
        },
        alternateRowStyles: {
          fillColor: [248, 249, 250],
        },
        margin: { left: 14, right: 14 },
      });

      // Footer
      const pageHeight = pdf.internal.pageSize.getHeight();
      pdf.setFontSize(8);
      pdf.setTextColor(107, 114, 128);
      pdf.text(pdfText("Generated by Attendance System", isArabic), 14, pageHeight - 10);
      pdf.text(`Date: ${new Date().toLocaleDateString()}`, pageWidth - 14, pageHeight - 10, { align: 'right' });

      pdf.save(`session_history_${session.grade}_${dayjs(date).format('YYYY-MM-DD')}.pdf`);
    } catch (error) {
      console.error("PDF Export Error: ", error);
      alert(`Failed to export PDF: ${error instanceof Error ? error.message : String(error)}`);
    } finally {
      setIsExportingPdf(false);
    }
  };

  return (
    <div className="flex items-center gap-2 print:hidden">
      <Button variant="outline" size="sm" onClick={exportXLSX} className="rounded-xl" disabled={isExportingExcel || isExportingPdf}>
        {isExportingExcel ? <Loader2 className="w-4 h-4 rtl:ml-2 ltr:mr-2 animate-spin" /> : <Download className="w-4 h-4 rtl:ml-2 ltr:mr-2" />}
        {dict.historyPage.exportExcel}
      </Button>
      <Button variant="outline" size="sm" onClick={exportPDF} className="rounded-xl" disabled={isExportingExcel || isExportingPdf}>
        {isExportingPdf ? <Loader2 className="w-4 h-4 rtl:ml-2 ltr:mr-2 animate-spin" /> : <Download className="w-4 h-4 rtl:ml-2 ltr:mr-2" />}
        {dict.historyPage.exportPdf}
      </Button>
    </div>
  );
}
