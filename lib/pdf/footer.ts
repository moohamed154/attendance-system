import { jsPDF } from 'jspdf';
import { pdfText } from './rtl';

interface FooterOptions {
  pdf: jsPDF;
  exportDict: any;
  isArabic: boolean;
  pageWidth: number;
  pageHeight: number;
}

/**
 * Draws the standardized footer with pagination on every page of the PDF.
 */
export function drawReportFooters({ pdf, exportDict, isArabic, pageWidth, pageHeight }: FooterOptions) {
  const pageCount = (pdf as any).internal.getNumberOfPages();
  const align = isArabic ? 'right' : 'left';
  const startX = isArabic ? pageWidth - 14 : 14;

  for (let i = 1; i <= pageCount; i++) {
    pdf.setPage(i);
    
    // Top border of footer
    pdf.setDrawColor(229, 231, 235);
    pdf.setLineWidth(0.5);
    pdf.line(14, pageHeight - 15, pageWidth - 14, pageHeight - 15);

    pdf.setFontSize(10);
    pdf.setTextColor(156, 163, 175);
    
    const footerText = pdfText(exportDict.generatedBy || "Generated by Attendance System", isArabic);
    pdf.text(footerText, startX, pageHeight - 10, { align, isRTL: isArabic } as any);

    const pageNumText = pdfText(`${exportDict.page || "Page"} ${i} / ${pageCount}`, isArabic);
    // Align page number to the opposite side
    const pageAlign = isArabic ? 'left' : 'right';
    const pageStartX = isArabic ? 14 : pageWidth - 14;
    pdf.text(pageNumText, pageStartX, pageHeight - 10, { align: pageAlign, isRTL: isArabic } as any);
  }
}
