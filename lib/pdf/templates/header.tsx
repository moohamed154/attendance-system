import React from 'react';

export interface PdfHeaderProps {
  centerName?: string;
  reportTitle: string;
  generatedBy?: string;
  generatedDate?: string;
  generatedTime?: string;
  filters?: { label: string; value: string }[];
}

export function PdfHeader({
  centerName = 'Attendance System',
  reportTitle,
  generatedBy,
  generatedDate = new Date().toLocaleDateString(),
  generatedTime = new Date().toLocaleTimeString(),
  filters = [],
}: PdfHeaderProps) {
  return (
    <div className="flex flex-col mb-8 border-b-2 border-blue-600 pb-4">
      <div className="flex justify-between items-start mb-4">
        <div>
          <h1 className="text-3xl font-bold text-blue-600 mb-1">{centerName}</h1>
          <h2 className="text-xl font-semibold text-gray-800">{reportTitle}</h2>
        </div>
        <div className="text-right text-sm text-gray-500">
          {generatedBy && <p>Generated by: {generatedBy}</p>}
          <p>Date: {generatedDate}</p>
          <p>Time: {generatedTime}</p>
        </div>
      </div>
      
      {filters.length > 0 && (
        <div className="flex flex-wrap gap-4 mt-2 pt-2 border-t border-gray-100">
          {filters.map((f, i) => (
            <div key={i} className="text-sm bg-gray-50 px-3 py-1 rounded-md border border-gray-200">
              <span className="text-gray-500 mr-2">{f.label}:</span>
              <span className="font-semibold text-gray-800">{f.value}</span>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
